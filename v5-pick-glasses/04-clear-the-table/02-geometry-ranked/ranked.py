"""Problem 4 with many candidate pushes and a fitted ranker to order them.

Solution 1 of this problem takes the one push problem 3's printed rule names:
the shortest safe push that gives a glass room. This solution enumerates every
safe push on the table instead, scores each one with problem 3's fitted trees,
and makes the first on the sorted list. Everything else about the two is the
same code.

**Why this solution is worth running here.** Solution 1 separates none of its
twenty tables, and it is not the loop that fails. Give its chooser the true
positions, perfect pushes and as many of them as it likes and it still
separates none, because one fixed nudge cannot undo a touching group of three
and every problem 4 table holds one. Sixty-seven of the eighty-six glasses it
leaves behind are left because there was nowhere clear to push them to. A
chooser that looks at every candidate is the reference most likely to find
somewhere, so what this solution really measures is whether these tables can be
separated at all.

**One line is different, and it is the chooser.** ``nudge.OneFixedNudge``
already does the hard part of problem 4: walk a ring of stands to see a table
the camera only sees part of, merge the looks into one belief, find how far
away a glass is with a ranging push because there is no force sensor, settle
the tipping question with problem 3's test push, and say when the table needs
nothing more. None of that depends on who picks the push, so this class
subclasses it and overrides ``_choose``.

**The ranker is problem 3's own fitted file, loaded and not refitted.** That is
the whole point: if the trees were fitted again here, a difference between
problem 3's solution 2 and this one could be the fit rather than the problem.
Problem 3 does not keep the file in git -- it is regenerated by ``make train``
in that folder, in seconds once its labelled rows exist -- so it can be absent,
and ``load_ranker`` says so in those words rather than failing on a pickle.

**The eight inputs all compute, and three of them mean something slightly
different here.** ``features.row`` is handed the glass, the other glasses and
the push. In problem 3 "the other glasses" is the whole table, because the
overhead camera hands it over. Here it is the table as the arm believes it,
which is every glass the arm has *seen so far*. So the contact angle, the room
at the destination and the count of neighbours within reach are all measured
against a table that may be missing a glass nobody has looked at yet. The sweep
of the whole ring is what keeps that gap small, and it is the same gap solution
1's own chooser works across; it is worth writing down because it is the only
thing about the inputs that problem 4 changes. A fourth input is worth a note
for a different reason: the distance from the destination to the rack is still
a number this cell can compute, but it is no longer a number about the task,
because problem 4 never racks a glass.
"""

from __future__ import annotations

from collections.abc import Callable

from borrowed import RANKER, candidates, features, nudge, ranker

from partners import Push, Seen

# Why a glass is left when the enumerator offered pushes for it and none of
# them was worth making. Problem 3's printed rule reports this and "no
# candidate at all" with the same words; the candidate set keeps them apart, so
# this solution does too. The glasses are the same glasses, grouped more
# finely.
STILL_CROWDED = "still without room after pushing"

# A chooser: the table as believed and the glasses not to push, and out comes
# the next push, the reasons for the glasses that have none, and how many
# candidates it was choosing between. The third value is why this is not simply
# ``plan.choose``'s signature. A ranking over one candidate is the printed rule
# wearing a hat, so the size of the group is what says whether the ordering had
# anything to order, and the chooser is the only thing that knows it.
Chooser = Callable[[list[Seen], set[int]], tuple[Push | None, dict[int, str], int]]


def load_ranker(path=RANKER) -> ranker.Ranker:
    """Problem 3's fitted trees, or a plain statement of what is missing.

    Nothing is fitted here and nothing falls back to a different model: a run
    without the file is not this solution.
    """
    if not path.exists():
        raise SystemExit(
            f"problem 3's fitted ranker is not at {path}.\n"
            "It is not kept in git. Make it there -- `make train` in "
            "03-push-glasses-apart/02-geometry-ranked -- and run this again."
        )
    return ranker.Ranker.load(path)


def reasons(glasses: list[Seen], skip: set[int], why: dict[int, str]) -> dict[int, str]:
    """Why every glass still worth pushing was not pushed, when nothing was chosen.

    ``candidates.survivors`` names the glasses that tip before they slide and
    the glasses with nowhere to go, and says nothing about the rest. When its
    list comes back empty, a glass it said nothing about is one it offered
    pushes for and then kept none of -- too slight to free the glass and too
    slight to loosen the table. That is a different answer from having nowhere
    to go, and the two are counted apart.
    """
    full = dict(why)
    for glass in glasses:
        if glass.id not in skip and glass.id not in full:
            full[glass.id] = STILL_CROWDED
    return full


class ByModel:
    """Choose with the trees: every survivor scored, the first on the sorted list.

    It keeps count of how often its pick is one the printed rule would also
    have been happy with, which costs nothing -- the candidates are already
    enumerated and the rule is three comparisons. That count is the cheapest
    reading there is of whether the ordering is doing anything, and it needs no
    second run of the bench to get it.
    """

    def __init__(self, score: ranker.Scorer) -> None:
        self.score = score
        self.agreed = 0
        self.differed = 0

    def __call__(self, glasses: list[Seen], skip: set[int]) -> tuple[Push | None, dict[int, str], int]:
        best, _, why = ranker.ranked(glasses, skip, self.score)
        if not best:
            return None, reasons(glasses, skip, why), 0
        if as_good_as_the_rule(best[0], best):
            self.agreed += 1
        else:
            self.differed += 1
        return best[0].push, why, len(best)


def as_good_as_the_rule(pick: candidates.Candidate, kept: list[candidates.Candidate]) -> bool:
    """Whether the printed rule would be indifferent between its own pick and this one.

    Asked on the rule's own key rather than by comparing the two candidates,
    and that is not fussiness. ``rule_choice`` takes the *first* shortest
    freeing push, so handed the same set in a different order it can name a
    different push of exactly the same length. Comparing the pushes would
    then count a tie as a disagreement, and the number reported would depend
    on the sort it is meant to be measuring. Comparing the key cannot.
    """
    rule = candidates.rule_choice(kept)
    if rule is None:
        return True
    if rule.freeing:
        return pick.freeing and pick.push.travel <= rule.push.travel + 1e-12
    return (pick.eased, -pick.push.travel) >= (rule.eased, -rule.push.travel)


def by_rule(glasses: list[Seen], skip: set[int]) -> tuple[Push | None, dict[int, str], int]:
    """Choose with the model deleted: problem 3's printed rule over the same candidates.

    This is the comparison that isolates the ordering. Both sides are handed
    exactly the same set, so what separates them is the sort and nothing else.
    It is not the same thing as running solution 1, which reaches the same
    pushes through ``plan.choose``; a test in this folder checks that the two
    pick the same push on the same table.
    """
    kept, why = candidates.survivors(glasses, skip)
    best = candidates.rule_choice(kept)
    if best is None:
        return None, reasons(glasses, skip, why), 0
    return best.push, why, len(kept)


class GeometryRanked(nudge.OneFixedNudge):
    """Solution 1's loop with the ranked candidate set in place of the printed rule."""

    name = "geometry ranked"

    def __init__(self, choose: Chooser | None = None) -> None:
        # Set before the base class runs, because the base constructor calls
        # ``begin`` and a chooser is the one thing this class adds.
        self.choose: Chooser = ByModel(load_ranker()) if choose is None else choose
        super().__init__()
        # How wide the choice really was, added up over every table since this
        # was built. The measurement run reads it.
        self.groups = 0
        self.candidates = 0
        self.widest = 0

    def _choose(self, glasses: list, skip: set[int]) -> tuple:
        push, why, group = self.choose(glasses, skip)
        self.groups += 1
        self.candidates += group
        self.widest = max(self.widest, group)
        return push, why

    def inputs(self) -> tuple[str, ...]:
        """The names of the eight inputs the ranker is shown, borrowed from problem 3.

        Here so that a reader of this folder can see them without going to the
        other problem, and so that nothing in this folder keeps a second list
        of them that could drift.
        """
        return features.NAMES
